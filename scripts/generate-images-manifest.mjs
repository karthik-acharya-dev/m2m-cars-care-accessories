import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');
const imagesDir = path.join(projectRoot, 'public', 'images');
const outputTsFile = path.join(projectRoot, 'src', 'data', 'imagesManifest.ts');

const REQUIRED_DIRS = [
  'hero',
  'workshop',
  'car-wash',
  'glass-tinting',
  'headlight-repair',
  'accessories',
  'detailing',
  'gallery',
  'inside'
];

// Ensure all expected subdirectories exist
for (const dir of REQUIRED_DIRS) {
  const dirPath = path.join(imagesDir, dir);
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true });
  }
}

const SUPPORTED_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif']);

/**
 * Recursively find all supported image files
 */
function scanImages(dir, relativeToRoot = 'images') {
  let results = [];
  if (!fs.existsSync(dir)) return results;

  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue; // skip .DS_Store, etc.

    const fullPath = path.join(dir, entry.name);
    const relWebPath = `/${relativeToRoot}/${entry.name}`;

    if (entry.isDirectory()) {
      results = results.concat(scanImages(fullPath, `${relativeToRoot}/${entry.name}`));
    } else {
      const ext = path.extname(entry.name).toLowerCase();
      if (SUPPORTED_EXTENSIONS.has(ext)) {
        // Parse basic dimensions from Google image filenames (e.g., ...w4032-h3024-k-no.jpg)
        let width = 1200;
        let height = 800;
        const dimMatch = entry.name.match(/w(\d+)-h(\d+)/i);
        if (dimMatch) {
          width = parseInt(dimMatch[1], 10);
          height = parseInt(dimMatch[2], 10);
        }

        // Determine category from path
        const parentDir = path.basename(dir);
        let category = 'gallery';
        if (REQUIRED_DIRS.includes(parentDir)) {
          category = parentDir;
        }

        results.push({
          filename: entry.name,
          src: relWebPath,
          category,
          width,
          height,
          aspectRatio: (width / height).toFixed(2),
          sizeBytes: fs.statSync(fullPath).size
        });
      }
    }
  }
  return results;
}

const allImages = scanImages(imagesDir);

// Filter duplicates by filename/size
const seen = new Set();
const uniqueImages = [];
for (const img of allImages) {
  const key = `${img.filename}-${img.sizeBytes}`;
  if (!seen.has(key)) {
    seen.add(key);
    uniqueImages.push(img);
  }
}

// Generate descriptive alt text and title based on category & index
const enrichedImages = uniqueImages.map((img, idx) => {
  let alt = `M2M Car Care & Accessories workshop Bengaluru - ${img.category} showcase #${idx + 1}`;
  let title = `Workshop Service Detail #${idx + 1}`;

  if (img.category === 'inside' || img.category === 'accessories') {
    alt = `M2M Car Care premium car accessories and interior custom fittings in Bengaluru - photo #${idx + 1}`;
    title = 'Automotive Interior & Accessories';
  } else if (img.category === 'workshop') {
    alt = `M2M Car Care service bay and automotive workshop facility in Sarjapur Road Bengaluru - photo #${idx + 1}`;
    title = 'Automotive Care Workshop';
  } else if (img.category === 'car-wash') {
    alt = `M2M Car Care precision car washing and exterior pressure clean - photo #${idx + 1}`;
    title = 'Exterior Car Wash';
  } else if (img.category === 'glass-tinting') {
    alt = `M2M Car Care sun film and automotive glass tinting installation - photo #${idx + 1}`;
    title = 'Glass Tinting & Sun Film';
  } else if (img.category === 'headlight-repair') {
    alt = `M2M Car Care headlight restoration and automotive lighting service - photo #${idx + 1}`;
    title = 'Headlight Restoration';
  } else if (img.category === 'detailing') {
    alt = `M2M Car Care deep vehicle detailing and surface finish - photo #${idx + 1}`;
    title = 'Vehicle Detailing';
  }

  return {
    id: `m2m-img-${idx + 1}`,
    src: img.src,
    alt,
    title,
    category: img.category,
    width: img.width,
    height: img.height,
    aspectRatio: parseFloat(img.aspectRatio)
  };
});

// Curate featured images for homepage (select horizontal, high-res, visually appealing images)
const landscapePhotos = enrichedImages.filter(img => img.aspectRatio >= 1.2 && img.width >= 1200);
const curatedFeatured = (landscapePhotos.length >= 8 ? landscapePhotos.slice(0, 8) : enrichedImages.slice(0, 8));

// Group counts by category
const categoryCounts = enrichedImages.reduce((acc, img) => {
  acc[img.category] = (acc[img.category] || 0) + 1;
  return acc;
}, {});

const fileContent = `// Auto-generated by scripts/generate-images-manifest.mjs
// Do not edit manually. Re-run 'npm run generate:images' when new images are placed in public/images/

export interface ImageManifestItem {
  id: string;
  src: string;
  alt: string;
  title: string;
  category: string;
  width: number;
  height: number;
  aspectRatio: number;
}

export const allImages: ImageManifestItem[] = ${JSON.stringify(enrichedImages, null, 2)};

export const featuredHomeImages: ImageManifestItem[] = ${JSON.stringify(curatedFeatured, null, 2)};

export const categoryCounts: Record<string, number> = ${JSON.stringify(categoryCounts, null, 2)};

export const defaultHeroImage: ImageManifestItem = ${
  JSON.stringify(curatedFeatured[0] || enrichedImages[0] || {
    id: 'fallback-hero',
    src: '/images/hero/hero-placeholder.jpg',
    alt: 'M2M Car Care & Accessories Workshop Bengaluru',
    title: 'M2M Workshop',
    category: 'hero',
    width: 1920,
    height: 1080,
    aspectRatio: 1.78
  }, null, 2)
};
`;

// Ensure destination directory exists
const outDir = path.dirname(outputTsFile);
if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

fs.writeFileSync(outputTsFile, fileContent, 'utf-8');
console.log(`Successfully generated manifest with ${enrichedImages.length} images at ${outputTsFile}`);
